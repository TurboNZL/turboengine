// Writes docs/THEMES.md, the list of everything in themes/ (the build runs this).
import fs from 'node:fs';
import path from 'node:path';
import { buildPalette, tokens } from '../engine/src/palette.ts';
import { buildThemes, root } from './lib/themes.mjs';

const { catalog } = await buildThemes({ minify: false });
const hsl = (v) => { const [h, s, l] = v.split(/[ %]+/).filter(Boolean).map(Number); const a = s / 100 * Math.min(l / 100, 1 - l / 100); const f = (n) => { const k = (n + h / 30) % 12; const c = l / 100 - a * Math.max(Math.min(k - 3, 9 - k, 1), -1); return Math.round(255 * c).toString(16).padStart(2, '0'); }; return '#' + f(0) + f(8) + f(4); };
const palettes = catalog.palettes.map((s) => ({ spec: s, p: buildPalette(s) }));
const head = '| Name | id | Tone | background · surface · accent · text |\n|---|---|---|---|\n';
const rows = (list) => list.map(({ spec, p }) => { const v = tokens(p); const sw = spec.own ? `(defined in \`themes/${folderOf(spec.id)}/palette.css\`)` : ['bg', 'surface', 'accent', 'fg'].map((k) => '`' + hsl(v[k]) + '`').join(' '); return `| ${p.label} | \`${p.id}\` | ${p.dark ? 'dark' : 'light'} | ${sw} |`; }).join('\n');
const folderOf = (id) => { for (const d of fs.readdirSync(path.join(root, 'themes'), { withFileTypes: true })) if (d.isDirectory() && JSON.parse(fs.readFileSync(path.join(root, 'themes', d.name, 'theme.json'), 'utf8')).palettes.some((p) => p.id === id)) return d.name; return '?'; };
const g = (name) => palettes.filter((x) => x.p.group === name);
const out = `# Every palette and UI style

Generated by \`pnpm build\` (scripts/gen-docs.mjs) from themes/. Do not edit by hand. Swatches are the derived values.

## The app's own palettes

${head}${rows(g('own'))}

## Colour palettes

${head}${rows(g('colour'))}

## Games, apps and devices

${head}${rows(g('inspired'))}

## Platform palettes

${head}${rows(g('platform'))}

## UI styles

| Name | id | Pairs with | Effects | What it is |
|---|---|---|---|---|
${catalog.styles.map((s) => `| ${s.label} | \`${s.id}\` | ${s.matching ? [...new Set(Object.values(s.matching))].map((x) => '`' + x + '`').join(', ') : '—'} | ${(s.effects ?? []).join(', ') || '—'} | ${s.description} |`).join('\n')}

## "Match this device"

The first rule that fits wins (themes/config.json):

| Device | Style | Light palette | Dark palette |
|---|---|---|---|
${catalog.config.devices.map((d) => `| ${d.name} | \`${d.ui}\` | \`${d.light}\` | \`${d.dark}\` |`).join('\n')}
| anything else | \`${catalog.config.fallbackDevice.ui}\` | \`${catalog.config.fallbackDevice.light}\` | \`${catalog.config.fallbackDevice.dark}\` |
`;
fs.mkdirSync(path.join(root, 'docs'), { recursive: true });
fs.writeFileSync(path.join(root, 'docs', 'THEMES.md'), out);
